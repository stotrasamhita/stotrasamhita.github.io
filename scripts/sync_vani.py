#!/usr/bin/env python3
"""Writes hugo/data/vani.yaml: the Stotra Samhita Vani video for each site
page that has one, and adds each video's description blurb to
stories/drafts.yaml as a draft story for review (see stories/README.md).

Reads a local clone of stotrasamhita/vani: work/youtube/upload_status.tsv
(uploaded videos; not committed there, so this runs by hand after uploads,
not in CI) and pipeline/youtube_blurbs.tsv. Only public videos are listed.

  python3 scripts/sync_vani.py --vani ../../vani
"""
import argparse
import csv
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
CONTENT = REPO_ROOT / "hugo" / "content"
OUT = REPO_ROOT / "hugo" / "data" / "vani.yaml"
DRAFTS = REPO_ROOT / "stories" / "drafts.yaml"
APPROVED = REPO_ROOT / "hugo" / "data" / "stories.yaml"
FRONT = re.compile(r"\A(\{\n.*?\n\})\n", re.S)

# Gītā videos -> content paths (the site splits the Gītā differently).
GITA = {"00dhyanam": None, "19mahatmyam": "gita/mahatmyam", "20varahamahatmyam": "gita/mahatmyam-varaha-puranam",
        "21gitarthasangraha": "gita/gsa", **{f"chapter{n:02d}": f"gita/gita/chapter-{n:02d}" for n in range(1, 19)}}
COMPILATIONS = {"gita-sampurna": "gita/gita/_index"}


# Videos uploaded under a TeX file name that has since been corrected.
RENAMED = {"dhanvataristotram": "dhanvantaristotram"}


def key(s):
    k = re.sub(r"[^a-z0-9]", "", s.lower())
    return RENAMED.get(k, k)


def stotra_index():
    """(folder, key of the TeX file name) -> content path, for stotra pages."""
    idx = {}
    for f in (CONTENT / "stotra").rglob("*.md"):
        m = FRONT.match(f.read_text(encoding="utf-8"))
        if not m or f.name == "_index.md":
            continue
        src = json.loads(m.group(1)).get("source_file", "")
        if src:
            idx[(Path(src).parent.name, key(Path(src).stem))] = str(f.relative_to(CONTENT).with_suffix(""))
    return idx


def add_drafts(found):
    """Adds blurbs for pages that have no draft or approved story yet. Drafts
    already there (perhaps edited) are left alone."""
    import yaml
    drafts = yaml.safe_load(DRAFTS.read_text(encoding="utf-8")) if DRAFTS.exists() else {}
    approved = yaml.safe_load(APPROVED.read_text(encoding="utf-8")) if APPROVED.exists() else {}
    drafts, approved = drafts or {}, approved or {}
    new = {p: {"text": b, "source": "Vani YouTube description (pipeline/youtube_blurbs.tsv)"}
           for p, b in found.items() if p not in drafts and p not in approved}
    if new:
        drafts.update(new)
        DRAFTS.parent.mkdir(exist_ok=True)
        DRAFTS.write_text(yaml.safe_dump(dict(sorted(drafts.items())), allow_unicode=True, sort_keys=False, width=100),
                          encoding="utf-8")
    print(f"stories: {len(new)} new drafts", file=sys.stderr)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--vani", type=Path, required=True, help="local clone of stotrasamhita/vani")
    a = ap.parse_args()
    blurbs = {r["stotra"]: r["blurb"].strip() for r in
              csv.DictReader(open(a.vani / "pipeline/youtube_blurbs.tsv", encoding="utf-8"), delimiter="\t")}
    idx = stotra_index()
    by_key = defaultdict(list)
    for (folder, k), path in idx.items():
        by_key[k].append(path)
    out, found, unmatched = {}, {}, []
    for r in csv.DictReader(open(a.vani / "work/youtube/upload_status.tsv", encoding="utf-8"), delimiter="\t"):
        if r["privacy"] != "public" or not r["video_id"]:
            continue
        coll, group, slug = r["collection"], r["group"], r["slug"]
        path = None
        if coll == "stotras":
            # The big stotras now live in their deity's folder.
            path = idx.get((group, key(slug))) or (by_key[key(slug)][0] if len(by_key[key(slug)]) == 1 else None)
        elif coll == "gita":
            path = GITA.get(slug)
        elif coll == "compilations":
            path = COMPILATIONS.get(slug)
        if not path:
            unmatched.append(f"{coll}/{group}/{slug}")
            continue
        out[path] = {"id": r["video_id"]}
        b = blurbs.get(f"{coll}/{group}/{slug}" if group else f"{coll}/{slug}")
        if b:
            found[path] = b
    add_drafts(found)
    lines = ["# Generated by scripts/sync_vani.py from the vani repo. Do not edit by hand.",
             "# content path -> {id: YouTube video id}"]
    for path in sorted(out):
        lines.append(f"{json.dumps(path)}: {json.dumps(out[path], ensure_ascii=False)}")
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"vani: {len(out)} pages with videos; not on the site: {len(unmatched)}", file=sys.stderr)
    for u in unmatched:
        print("  " + u, file=sys.stderr)


if __name__ == "__main__":
    main()
